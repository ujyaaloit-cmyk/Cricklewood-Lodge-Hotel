function figureFor(photo, caption) {
  return `<figure><img src="${photo.src}" alt="${photo.alt}" loading="lazy" decoding="async"><figcaption>${caption || photo.alt}</figcaption></figure>`;
}

function isMainRoomPhoto(photo) {
  const alt = photo.alt.toLowerCase();
  const roomMatch = alt.includes('bed') || alt.includes('hotel room') || alt.includes('bedroom') || alt.includes('room with');
  const secondaryMatch = alt.includes('bathroom') || alt.includes('shower') || alt.includes('ceiling') || alt.includes('light') || alt.includes('urinal') || alt.includes('dining') || alt.includes('hallway') || alt.includes('flowers');
  return roomMatch && !secondaryMatch;
}

function orderedRoomPhotos(photos) {
  const main = photos.filter(isMainRoomPhoto);
  const rest = photos.filter((photo) => !main.includes(photo));
  return [...main, ...rest];
}

function expandableGallery(photos, caption, initialCount = 4) {
  const visible = photos.slice(0, initialCount).map((photo) => figureFor(photo, caption)).join('');
  const hidden = photos.slice(initialCount).map((photo) => `<div class="gallery-extra" hidden>${figureFor(photo, caption)}</div>`).join('');
  const remaining = Math.max(photos.length - initialCount, 0);
  const button = remaining ? `<button class="show-more" type="button" data-show-more>Show more ${remaining} photos</button>` : '';
  return `${visible}${hidden}${button}`;
}

function previewTile(photo, label, className = '') {
  return `<img class="${className}" src="${photo.src}" alt="${photo.alt}" loading="lazy" decoding="async">${label ? `<span>${label}</span>` : ''}`;
}

function roomCard(room, details, photos) {
  const features = details.features.map((fact) => `<li>${fact}</li>`).join('');
  const first = photos[0];
  const second = photos[1] || first;
  const third = photos[2] || first;
  const fourth = photos[3] || first;
  const remaining = Math.max(photos.length - 3, 0);
  return `<article class="room-listing">
    <div class="room-preview-grid">
      <button class="room-photo-main" type="button" data-open-room-gallery="${room}" aria-label="Open ${room} photos">${previewTile(first, '')}</button>
      <button class="room-photo-small" type="button" data-open-room-gallery="${room}" aria-label="Open ${room} photos">${previewTile(second, '')}</button>
      <button class="room-photo-small" type="button" data-open-room-gallery="${room}" aria-label="Open ${room} photos">${previewTile(third, '')}</button>
      <button class="room-photo-more" type="button" data-open-room-gallery="${room}" aria-label="Open all ${room} photos">${previewTile(fourth, `+${remaining} photos`)}</button>
    </div>
    <div class="room-listing-body">
      <div><p class="eyebrow">Room type</p><h2>${room}</h2><div class="room-spec-table"><div><span>Sleeps</span><strong>${details.sleeps}</strong></div><div><span>Beds</span><strong>${details.beds}</strong></div><div><span>Bathroom</span><strong>${details.bathroom}</strong></div></div><ul class="room-meta">${features}</ul></div>
      <div class="room-listing-actions"><button class="btn btn-outline" type="button" data-open-room-gallery="${room}">View photos</button><a class="btn btn-primary" href="book.html">Check availability</a></div>
    </div>
  </article>`;
}

function openRoomModal(room) {
  const modal = document.querySelector('[data-gallery-modal]');
  if (!modal) return;
  const photos = orderedRoomPhotos(bookingGalleries[room] || []);
  modal.querySelector('[data-modal-title]').textContent = room;
  modal.querySelector('[data-modal-count]').textContent = `${photos.length} photos`;
  modal.querySelector('[data-modal-gallery]').innerHTML = photos.map((photo) => figureFor(photo, room)).join('');
  modal.hidden = false;
  document.body.classList.add('modal-open');
  modal.querySelector('[data-close-modal]').focus();
}

function closeRoomModal() {
  const modal = document.querySelector('[data-gallery-modal]');
  if (!modal) return;
  modal.hidden = true;
  document.body.classList.remove('modal-open');
}

function renderRoomPages() {
  const roomsRoot = document.querySelector('[data-room-galleries]');
  if (roomsRoot) {
    roomsRoot.innerHTML = `<div class="room-listings">${Object.entries(roomDetails).map(([room, details]) => {
      const photos = orderedRoomPhotos(bookingGalleries[room] || []);
      return roomCard(room, details, photos);
    }).join('')}</div><div class="gallery-modal" hidden data-gallery-modal><div class="gallery-modal-panel" role="dialog" aria-modal="true" aria-labelledby="roomGalleryTitle"><div class="gallery-modal-head"><div><p class="eyebrow" data-modal-count></p><h2 id="roomGalleryTitle" data-modal-title></h2></div><button class="modal-close" type="button" data-close-modal aria-label="Close gallery">Close</button></div><div class="modal-gallery" data-modal-gallery></div></div></div>`;
  }

  const galleryRoot = document.querySelector('[data-full-gallery]');
  if (galleryRoot) {
    galleryRoot.innerHTML = Object.entries(bookingGalleries).map(([group, photos]) => {
      const orderedPhotos = roomDetails[group] ? orderedRoomPhotos(photos) : photos;
      const gallery = expandableGallery(orderedPhotos, group, roomDetails[group] ? 4 : photos.length);
      return `<section class="gallery-section"><div class="section-head"><p class="eyebrow">${photos.length} matched photos</p><h2>${group}</h2></div><div class="room-gallery">${gallery}</div></section>`;
    }).join('');
  }

  document.querySelectorAll('[data-show-more]').forEach((button) => {
    button.addEventListener('click', () => {
      const gallery = button.closest('.room-gallery');
      gallery.querySelectorAll('.gallery-extra').forEach((item) => {
        item.hidden = false;
      });
      button.remove();
    });
  });

  document.querySelectorAll('[data-open-room-gallery]').forEach((button) => {
    button.addEventListener('click', () => openRoomModal(button.dataset.openRoomGallery));
  });

  document.querySelectorAll('[data-close-modal]').forEach((button) => {
    button.addEventListener('click', closeRoomModal);
  });

  document.querySelectorAll('[data-gallery-modal]').forEach((modal) => {
    modal.addEventListener('click', (event) => {
      if (event.target === modal) closeRoomModal();
    });
  });

  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') closeRoomModal();
  });
}

